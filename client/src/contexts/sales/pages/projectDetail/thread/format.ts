/**
 * やり取りの日付の書き方（1か所）
 *
 * **やり取りタブのカードと概要タブのダイジェストが同じ関数を読みます。**
 * 書き写すと、片方だけ直したときに**同じ期限が画面によって違う形で出ます**
 * （`kinds.ts` と同じ理由）。
 */

/**
 * `2026-08-01` を `8/1` にする。**年が基準と違うときだけ年を出す**。
 *
 * 期限は本文の中に混ぜて出すので、`2026-08-01` のまま置くと
 * **10 文字のうち読む情報が2文字しかない**まま行を圧迫します。
 * ただし年をいつも省くと、**年をまたいだ期限が「もう過ぎた日」に見えます**
 * （2027-01-05 を「1/5」と出すと、2026 年の 1/5 と区別が付かない）。
 *
 * @param ymd  出したい日付（`YYYY-MM-DD`）
 * @param base 基準の日付。ふつうはその記録の日
 */
export function shortYmd(ymd: string | null | undefined, base?: string | null): string {
  if (!ymd) return '';
  const m = /^(\d{4})-(\d{2})-(\d{2})$/.exec(ymd);
  // **読めない形はそのまま出す。** 勝手に整えると、壊れた値が入っていることに気づけない
  if (!m) return ymd;
  const [, y, mm, dd] = m;
  const md = `${Number(mm)}/${Number(dd)}`;
  return base?.slice(0, 4) === y ? md : `${y}/${md}`;
}
