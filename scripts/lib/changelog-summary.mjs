/**
 * 版の**要約**の作り方（`scripts/collect-changelog.mjs` が使う）
 *
 * ── なぜ別ファイルにしてあるか ──────────────────────────────
 *
 * `collect-changelog.mjs` は読み込んだ瞬間に走る道具（引数を見て、ファイルを書き換えて、
 * 集めた下書きを消す）なので、**試験から import できません**。
 * ここに出しておくと、**画面を見ても間違いに気づけない**部分
 * （見出しの取り出し・要約の組み立て）を `shared/tests/` から固定できます。
 */

/**
 * **要約の置き場所**（任意）。`docs/changelog.d/` に置きます。
 *
 * 全文が上限を超えたとき、`CLAUDE.md` 側の1行に**そのまま**使います。
 * **PR の下書きではない**ので、集める対象からは外します
 * （混ぜると、要約が「収録した変更の1つ」として全文にも入ります）。
 */
export const SUMMARY_FILE = '_summary.md';

/**
 * 下書きの**先頭の太字**を見出しとして取り出す。
 *
 * 決めごと（`docs/changelog.d/README.md`）で下書きは `**タイトル**（…）。本文` の形に
 * そろえてあるので、**推測せずに人が書いた見出しをそのまま**使えます。
 *
 * ⚠️ **`**` を挟んだ最短一致で取る。** 貪欲に取ると、本文の中の別の太字まで
 * 巻き込んで**見出しが段落まるごと**になります（要約が全文と同じ長さになる）。
 *
 * 太字で始まっていないものだけ、最初の句点までで代用します
 * （**作り話をしない** — 中身を要約し直すのは機械にはできません）。
 * ⚠️ **句点が1つも無い下書き**（英語だけ・箇条書きだけ）もあるので、
 * そのときは丸ごと1文として扱ったうえで長さで切ります。
 */
export function titleOf(body) {
  const bold = String(body).match(/^\*\*(.+?)\*\*/);
  if (bold) return bold[1].trim();
  const first = String(body).split('。')[0].replace(/\*\*/g, '').trim();
  return first.length <= 60 ? first : `${first.slice(0, 60)}…`;
}

/**
 * 全文が上限を超えたときに `CLAUDE.md` へ置く**要約の本文**を組み立てる。
 *
 * ⚠️ **中身を要約し直しません。** 機械にできるのは「**何が入っているか**」を
 * 並べることだけで、「**その版が何だったか**」を1文で言うのは人の仕事です。
 * だからここが作るのは**収録した見出しの一覧**で、
 * `_summary.md` を置けばそちらを**そのまま**使います。
 *
 * ⚠️ **先頭を太字にする。** 画面の「バージョン履歴」は
 * **先頭の太字を見出しとして切り出す**（`generate-version-history.mjs` の `TITLE_RE`）ので、
 * 太字で始めないと**本文の頭 90 文字が版の名前**になります。
 */
export function buildSummaryBody(titles) {
  return `**${titles.length} 本ぶんの変更**`
    + `（**1件ずつの詳細は下のアーカイブに全文あります**）。`
    + `収録: ${titles.map((t) => `「${t}」`).join('／')}`;
}
