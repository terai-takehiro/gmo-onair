export interface CommandDef {
  id: string;
  kind: CommandKind;
  /** 画面に出す名前 */
  label: string;
  /** どの区分の中か。⌘K の地図と 全体マップ の両方がこれで畳む */
  section: SiteSectionId;
  /** 行の左に出す印。lucide のアイコン名 (`Icon` そのものを渡す) */
  icon?: LucideIcon;
  /**
   * 1行説明。**`open` にも必ず書く** —
   * 全体マップは「名前だけ80個」を並べても読めないので、
   * 「ここで何ができるか」が無い行を作らない。
   */
  hint?: string;
  /** 行き先 (絶対パス)。別アプリのパスもそのまま書く */
  path: string;
  /** 当たり語。ローマ字・かな・旧名称などを空白区切りで */
  keywords?: string;
  /** このモジュール権限を持つ人にだけ出す */
  module?: string;
  /** いずれかの権限を持つ人に出す (module より優先) */
  modules?: string[];
  /** system_admin にだけ出す */
  adminOnly?: boolean;
  /** レールにも出ている行き先。全体マップで「左のレールから開けます」と添える */
  onRail?: boolean;
}

/** GET /search の結果を1行に写したもの */
export interface PaletteHit {
  id: string;
  /** 案件名・顧客名 */
  name: string;
  /** 顧客名・略称など2行目 */
  sub?: string;
  /** GLS番号・コード */
  code?: string;
  /** ステージ・種別 */
  badge?: string;
  path: string;
}

/**
 * 検索の結果。**権限で外れた種類も返す** (36章)。
 *
 * 「案件 0件」と出すと「無い」と読めてしまうが、実際は「見せてもらえない」なので
 * 意味が違う。**件数は出さず、種類の名前だけ**を伝えて画面に書く。
 */
export interface PaletteSearchResult {
  hits: PaletteHit[];
  /** 権限が無くて探していない種類 (名前だけ) */
  hiddenKinds?: string[];
  /** 見つかった総数 (画面が「すべて見る」を出すのに使う) */
  total?: number;
}

export interface PaletteAccess {
  role?: string;
  permissions?: Record<string, string>;
}
