import type { Config } from 'tailwindcss';

/**
 * v4 対象3アプリだけに効く上乗せ設定
 *
 * ── なぜ `tailwind.preset.ts` に書けないのか ────────────────────
 *
 * あちらは**凍結4アプリも継承しています**。凍結の決めごとは
 * 「見た目を今日のまま保つ」なので、あそこに手を入れると4アプリの見た目が動きます。
 * v4 だけに効かせたいものはここに置き、3アプリの `tailwind.config.ts` が
 * `presets: [preset, v4Preset]` の順で継承します。
 *
 * ── 中身: 存在しない太さを潰す ──────────────────────────────
 *
 * **LINE Seed JP は 400 / 700 / 800 しか配信されていません。**
 * `font-medium`(500) と `font-semibold`(600) はコードに 610 か所あり、
 * ブラウザは**近い太さで代用するか、太らせて偽物を作ります**
 * (合成太字。字面が濁って、同じ 700 の文字と並ぶと揃いません)。
 *
 * ここで **500 → 400 / 600 → 700** に潰すと:
 *   ・**実際に描かれる太さと、開発ツールに出る値が一致する**
 *     (いまは「500」と出るのに 400 か合成太字で描かれている)
 *   ・610 か所を1つずつ書き換えなくても、字面がそろう
 *
 * 610 か所を減らす作業自体は続けます (`check-ui-tokens` の
 * `missing-font-weight` が数を見ている)。これはその間の下支えです。
 */
const v4Preset: Config = {
  content: [],
  theme: {
    extend: {
      fontWeight: {
        medium: '400',
        semibold: '700',
      },
    },
  },
};

export default v4Preset;
