/**
 * 幅が足りるまで列を出さない (`RowSlot` の `hideOnMobile` を1段うしろへずらす)
 *
 * ── なぜ要るか（実測した壊れ方）──────────────────────────────
 *
 * `RowSlot hideOnMobile` は **640px (`sm`) で列を出し始めます**。同時に
 * `Row stackOnMobile` は **640px で折り返しをやめます**（`sm:flex-nowrap`）。
 * つまり 640px ちょうどで**列が増えるのと、1行に詰め込むのが同時に起きます**。
 *
 * 伸びるのは `RowMain`（商品名）だけで、`RowSlot` は `shrink-0` なので、
 * **足りないぶんは全部 `RowMain` から引かれます**。列を並べた表では
 * 640〜1023px で商品名が消えていました（実測・行の左右余白 32px、隙間 12px で計算）:
 *
 *   貸出の塊（`equipmentList/RentalGroupRow.tsx`） 固定 504 + 隙間 72 + 余白 32 = 608px
 *     → 640px で商品名に残るのは **0px**（レビューでの指摘 #161・P2）
 *   備品の台帳（`catalog/CatalogRows.tsx`）        固定 648 + 隙間 84 + 余白 32 = 764px
 *     → 640px で **−156px**・768px でも **−28px** ＝ **行が横にはみ出す**
 *   貸出の設定（`settings/RentalRulesTab.tsx`）    固定 512 + 隙間 60 + 余白 32 = 604px
 *     → 640px で **4px**
 *
 * ⚠️ **どれも「崩れている」としか見えません。** `RowSlot` の幅は正しく効いていて、
 * エラーも警告も出ず、**375px（スマホ）と 1280px（PC）では正常**なので、
 * その2つで確かめる限り**一度も見えません**。
 *
 * ── なぜ `lg`（1024px）か ────────────────────────────────────
 *
 * この3つは `md`（768px）でも商品名が 128px 前後しか残らず、
 * 台帳が自分で決めた下限（`equipmentList/types.ts` の `NAME_MIN_PX = 200`）に届きません。
 * **1024px 以上は今までと1ピクセルも変わりません** — 変えたのは
 * 「列が出てくる幅」だけで、狭い側を**列が消えるほうへ倒して**います
 * （`docs/design/v4/_rules.md`「3. スマホ」＝ 出す情報を絞る）。
 *
 * ⚠️ **`shared/src/client/ui/row.tsx` は触っていません。** あそこに段を足すと
 * 凍結4アプリの Tailwind も走査するので**あちらの CSS が増えます**
 * （`client-equipment/tailwind.config.ts` の注意書き）。
 *
 * ── 使い方 ──────────────────────────────────────────────────
 *
 * 本文の列は `hideOnMobile` と**併せて**渡します（`cn` が後勝ちで `sm:flex` を消す）。
 * **表頭の同じ列にも必ず渡すこと** — 片方だけだと、見出しだけ出て中身が無い列ができます。
 *
 * ```tsx
 * <RowSlot w={128} hideOnMobile className={HIDE_UNTIL_WIDE}>…</RowSlot>
 * ```
 */
export const HIDE_UNTIL_WIDE = 'sm:hidden lg:flex';

/**
 * もう1段うしろ (`2xl` = 1536px〜)。**`lg` でもまだ足りない表だけ**に使います。
 *
 * ── なぜ `lg` の1段では足りなかったか（実測）────────────────
 *
 * 上の計算は**本文の幅を画面の幅と同じだと見なしています**が、`lg` から
 * **左メニュー 248px が現れます**。実際の本文は `画面 − 248 − 余白48` で、
 * 1024px のとき **728px** しかありません。さらに貸出の決めごとは
 * **右に 400px のパネル**が並ぶので、そこからさらに 416px 引かれます。
 *
 *   ケーブル・コネクタ（`catalog/CatalogRows.tsx`）  1024px の本文 728px に対し 764px
 *     → 商品名 **0px**・行が **36px はみ出す**
 *   貸出の決めごと（`settings/RentalRulesTab.tsx`）  1280px でもリストは 568px
 *     → 商品名 **0px**・種別と設置場所が右端で切れる（横に送る手段も無い）
 *
 * ⚠️ **375px と 1440px では正常に見えます。** 壊れているのは
 * **1024〜1350px の帯だけ**で、ここを測らない限り一度も見えません。
 *
 * ── 使い方 ──────────────────────────────────────────────────
 *
 * `HIDE_UNTIL_WIDE` と同じく `hideOnMobile` と併せて渡し、**表頭にも同じ段**を渡します。
 * どの列をこちらへ送るかは「その幅で商品名に 200px（`NAME_MIN_PX`）残るか」で決めること。
 */
export const HIDE_UNTIL_EXTRA_WIDE = 'sm:hidden 2xl:flex';
