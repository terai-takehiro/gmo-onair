-- 依頼（delegation）の通知ひな形 — 根源整理 Phase 1（docs/core-redesign-plan.md §3-4）
--
-- ── なぜ通知が要るのか ──────────────────────────────────────
--
-- 依頼は作成・承諾・辞退・相談・振り直しの**どこにも通知が無かった**。
-- 受け手がバッジを偶然見るまで依頼は届かず、辞退しても依頼主に知らされない
-- （「頼んだのに忘れられた」がシステムの中で再現されていた）。
-- できごと型なので定時実行は要らず、my-tasks.service が操作の場で直接出す。
--
-- ── 2本に分ける ─────────────────────────────────────────────
--
-- 「届いた」（受け手へ）と「返事が来た」（依頼主へ）は宛先も文面も逆向きなので
-- 1本にまとめない。承諾/辞退/相談の別は差し込み語 {返答} で表す —
-- 3本に割ると、返答の種類を増やすたびに migration が要る。
--
-- ── 二重に出さない ──────────────────────────────────────────
--
-- migration 177 の一意索引（人 × ひな形 × 対象 × ref_date）に乗せる。
-- dg_reply は ref_date に返答の種類を入れる（相談→承諾は両方届き、
-- 同じ返答の連打は1回になる）。dg_new の振り直しは ref_date に振り直し時刻を
-- 入れる（同じ人へ振り直し直しても改めて届く — 新しい依頼として答えてほしいため）。
--
-- ── 既にあれば触らない ──────────────────────────────────────
--
-- 文面を直した人の変更を、次のデプロイで上書きしないため（186 と同じ）。

