-- ============================================================
-- 189: 拠点に略称を持たせる（設定 → 拠点・部屋 で直せる対照表）
--
-- ── なぜ列を足すのか ────────────────────────────────────────
--
-- 拠点の正式名は「GMOサムライスタジオ用賀」で **12文字**あります。案件詳細の
-- 事実の帯（1枠 200〜270px）や一覧の行に出すと、**拠点名だけで枠が埋まって
-- 部屋名が消えます**。そのため会場の表示は部屋名だけにしていましたが、
-- 「用賀 WORLD STUDIO」と出せるほうが読み手には分かりやすい（ご要望）。
--
-- **コードで正式名を機械的に短くしません。**「GMOサムライスタジオ」を削る細工は、
-- 拠点が1つ増えた日・名前が変わった日に黙って崩れます（そして誰も気づけません）。
-- **何を略称と呼ぶかは人が決めるもの**なので、列に持たせて画面から直せるようにします。
--
-- ── 部屋にはもう略称がある ──────────────────────────────────
--
-- `studio_rooms.abbreviation` は既にあり、カレンダーの部屋チェインが使っています。
-- **拠点側だけが持っていませんでした。** 同じ名前（`abbreviation`）にそろえるので、
-- 設定画面は「正式名 ↔ 略称」の対照表を拠点と部屋で同じ形で出せます。
--
-- ── NULL を空文字で埋めない ────────────────────────────────
--
-- **NULL = 略称を決めていない**で、画面は正式名を出す（または前置きを付けない）。
-- 空文字を既定にすると「空の略称を決めた」と区別できなくなります。
-- ============================================================

ALTER TABLE studio_locations ADD COLUMN IF NOT EXISTS abbreviation TEXT;

-- ── 既にある4拠点の初期値 ───────────────────────────────────
--
-- **id で当てます**（名前で当てると、名前を直した拠点に入りません）。
-- この4つは migration 030 / 116 で id 固定で入るので、本番・検証・手元で同じです。
-- **すでに入っている略称は上書きしません**（人が直したものを戻さない）。
-- id が違う拠点（あとから足したもの）は NULL のまま = 画面から決めてもらう。
UPDATE studio_locations SET abbreviation = '用賀'   WHERE id = 'loc-yoga'     AND abbreviation IS NULL;
UPDATE studio_locations SET abbreviation = '渋谷'   WHERE id = 'loc-shibuya'  AND abbreviation IS NULL;
UPDATE studio_locations SET abbreviation = '青山'   WHERE id = 'loc-aoyama'   AND abbreviation IS NULL;
UPDATE studio_locations SET abbreviation = '外現場' WHERE id = 'loc-external' AND abbreviation IS NULL;
