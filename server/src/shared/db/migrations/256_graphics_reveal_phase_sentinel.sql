-- ============================================================
-- 251: graphics_cue_state.reveal_phase の「未使用」表現を直す
--
-- 段6-1（migration 248）は reveal_phase の既定値・TAKE時のリセット値を 0 にしていた。
-- ところがクライアント側（FullscreenList・ScoreBoard）は「revealPhase が数値なら
-- 段階公開モード」と解釈するため、**TAKEした瞬間はどのページも必ず revealPhase=0
-- （＝1件目までしか見せない）になってしまい**、「続き」を一度も使わない一覧表・
-- スコアボードまで巻き添えで1件しか表示されなくなっていた（意図された後方互換
-- 「未指定＝全件表示」が、cueが必ず0を持つせいで一度も成立していなかった）。
--
-- 修正: 「まだ続きを使っていない」を表す値を 0 ではなく -1 にする。
--   -1 = 段階公開を使っていない（クライアント側は「全件表示」と解釈）
--    0 = 続きボタンを1回押した（1件目まで表示）
--    n = 続きボタンを (n+1) 回押した（n+1件目まで表示）
-- 「続き」の +1 処理（bumpRevealPhase の LEAST(reveal_phase + 1, 99)）は -1+1=0 に
-- 自然に遷移するため、この1行の意味変更だけで整合する。
-- ============================================================

ALTER TABLE graphics_cue_state ALTER COLUMN reveal_phase SET DEFAULT -1;

-- 既存の cue 行は今の値が「本当に続きを押した結果の0」なのか「TAKEでリセットされた
-- だけの0」なのか区別が付かない。運用中の段階公開の途中経過よりも「巻き添えで1件しか
-- 出ていないページを直す」ほうを優先し、一律 -1（全件表示）へ戻す
-- （reveal_phase は演出の一時状態であって保存すべきコンテンツではないため、
-- 巻き戻しても実害はない）。
UPDATE graphics_cue_state SET reveal_phase = -1;
