-- 191: 投入口の「拾わなかったもの」を行に残す（レビューでの指摘 #77 / #75）
--
-- ── なぜ列を足すのか ────────────────────────────────────────
--
-- 打ち込んで投げたときは、拾わなかった行（「決定事項なのでタスクにしなかった」）も
-- 規則ベースへの縮退も**その場の応答に載せて**画面に出していました。
--
-- ところが**録音から投げると、解析は裏で走ります**（migration 180）。応答は先に
-- 202 で返り、画面はあとから `GET /tasks/intakes/:id` を読みに行くので、
-- **その場の応答にしか無い警告は消えます** — 同じ投入でも
-- 「打ったときは出るのに、録音だと出ない」という食い違いになっていました。
--
-- 拾わなかったことは**下書きと同じくらい大事な情報**です。出ないと、
-- 「1件しか出てこないのは AI が読み落としたからだ」と思って**もう一度投げます**
-- （そして2回目も同じ行が落ちます）。
--
-- ── 添付の取りこぼしもここに入れる ──────────────────────────
--
-- Anthropic は画像を 4 種類しか受け取れないので、それ以外（iPhone の HEIC など）は
-- **黙って落として**いました。添付した人には「読まれていない」ことが分かりません。
-- 落としたことも同じ列に残し、確認画面に並べます。
--
-- **形は `[{ line, reason }]`** — 画面（`IntakeReview`）がすでに読んでいる形に揃えます
-- （別の形にすると、出す場所を2つ書くことになります）。

ALTER TABLE task_intake ADD COLUMN IF NOT EXISTS warnings JSONB;

COMMENT ON COLUMN task_intake.warnings IS
  '拾わなかった行・落とした添付・規則ベースへの縮退。[{line, reason}] の配列';
