-- ============================================================
-- 247: ストックに「見直す日」を持たせる（ストックを見送りと同じにしない）
--
-- ── なぜ要るか（ユーザー報告）──────────────────────────────
-- 「入ってきた情報、受け取った書類も、結局何をしたいのかわからないアプリになってる」
--
-- migration 171 で行き先を5つ（未仕分け / ストック / チケット / 案件にした / 見送り）に
-- しましたが、**ストックにだけ出口がありません**でした。画面は
-- 「あとで効く話ならストックしてタグを付ける」と謳っているのに、
-- ストックしたものを人の目に戻す仕掛けが1つも無く（見直す日も・通知も・
-- 週報への反映も無い）、タグは付けた本人が思い出して引きに行くまで誰も見ません。
--
-- ⚠️ **見直す日が無いストックは、実質「見送り」と同じです。**
-- どちらも「未仕分けから消えて二度と出てこない」で終わります。
-- 行き先が2つあるように見えて、実際に違うのは名前だけでした。
-- **この列が「ストックは見送りではない」を成立させている唯一のもの**なので、
-- 消すときは代わりの戻し方を必ず用意すること。
--
-- ── どう戻すか ──────────────────────────────────────────────
-- `stock_review_on <= 今日` になったストックを、**未仕分けと同じ扱いで
-- 「今日さばくもの」に含めます**（画面の見出し・ホームのタイル・
-- `GET /dailyops/alerts` の3か所とも同じ判定）。
--
-- **見直す日が入っていないストック（`NULL`）も机に出します。**
-- 「決めていない」を「永久に出さない」と読むと、この列を足す前と同じ
-- 行き止まりに戻るためです（判定は
-- `shared/src/utils/inboxDesk.ts` の `isStockReviewDue()` が正で、
-- 画面とサーバーで同じ規則を使います）。
ALTER TABLE misc_inquiries ADD COLUMN IF NOT EXISTS stock_review_on DATE;

COMMENT ON COLUMN misc_inquiries.stock_review_on IS
  'ストックしたものを机に戻す日。NULL（決めていない）も「今日さばくもの」に含める — 戻す日が無いストックは見送りと同じになるため';

-- 「今日さばくもの」は毎朝この条件で数える（未仕分けの件数と一緒に出す）
CREATE INDEX IF NOT EXISTS idx_misc_inquiries_stock_review
  ON misc_inquiries(stock_review_on)
  WHERE deleted_at IS NULL AND state = 'stock';

-- ── 既にストックされている行の扱い ──────────────────────────
-- 既存のストックは**いつ見直すか誰も決めていない**状態です。
-- そのまま NULL にすると（上の規則で）リリースした日に全部が机へ出ます。
-- 溜まった分を初日に一斉に出すと、その日は1件も片づきません
-- （migration 244 で「遡って印を付けない」と決めたのと同じ理由）。
-- **リリース日から1か月後**に置いて、通常の見直しの流れに合流させます。
-- ⚠️ **`CURRENT_DATE` を使わない。** DB のタイムゾーンは UTC なので、
-- 日本時間の 00:00〜09:00 に流すと1日ずれます
-- （この製品の決めごと: SQL では `NOW() AT TIME ZONE 'Asia/Tokyo'`）。
UPDATE misc_inquiries
   SET stock_review_on = ((NOW() AT TIME ZONE 'Asia/Tokyo')::date + INTERVAL '1 month')::date
 WHERE deleted_at IS NULL AND state = 'stock' AND stock_review_on IS NULL;
