-- ============================================================
-- 249: 終了した案件の BOX フォルダを「98_終了案件」へ移した印
--
-- ── なぜ要るか（ユーザー依頼 2026-08-31）────────────────────
-- 「案件が完了した(日付をベースに案件日の翌日)ものについては
--   98_終了案件 というフォルダを BOX に新たに作成した上で
--   そこに移動するようにしたい」
--
-- 失注・見送りの `99_失注・見送り`（migration 248）と対になる置き場。
-- ⚠️ **こちらは絶対に削除しません。** 終了した案件のフォルダには納品物・
-- 請求書・検収書が入っており、法定保存の対象でもあります。**移すだけ**です。
--
-- ── なぜ `box_cleanup_state` に相乗りさせないか ──────────────
-- あちらは「失注から戻したときに元へ返す」ための列で、'archived'（引っ越した）
-- と 'deleted'（空だったので消した）の2値に CHECK が掛かっています。
-- **終了の引っ越しは失注とは別の出来事**（同じ案件が失注→戻す→終了、と
-- 両方を経験しうる）なので、混ぜると復元がどちらの話か分からなくなります。
--
-- 日付だけを持ちます（`NULL` = まだ移していない）。案件を完了から戻したときは
-- `NULL` に戻し、フォルダも親フォルダへ返します。
-- ============================================================

ALTER TABLE projects ADD COLUMN IF NOT EXISTS box_done_at TIMESTAMPTZ;

COMMENT ON COLUMN projects.box_done_at IS
  'BOX フォルダを「98_終了案件」へ移した日時。NULL = まだ移していない。完了から戻すと NULL に戻り、フォルダも親へ返る';

-- 移していない終了案件だけを引く部分索引。ほとんどの行は NULL のままなので、
-- 全行に索引を張ると書き込みだけが重くなる
CREATE INDEX IF NOT EXISTS idx_projects_box_done_pending
  ON projects(stage) WHERE box_done_at IS NULL AND deleted_at IS NULL;
