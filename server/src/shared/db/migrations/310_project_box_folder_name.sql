-- ============================================================
-- 310: 案件の BOX フォルダ名を「どの名前に合わせ終えたか」の印
--
-- ── なぜ要るか（ご依頼 2026-09-24）──────────────────────────
-- 「BOX の案件フォルダに案件実施日をつけたい。日付が先頭だと BOX でソートできる」
-- フォルダ名を `{番号}_{案件名}` から `{実施日}_{番号}_{案件名}` に変える
-- （`box-folder.service.ts` の `buildProjectFolderName`）。
--
-- 実施日はカレンダーの予約・Excel 取込・MCP など何か所からも変わるので、
-- 変わるたびに BOX を見に行くのではなく、**最後に合わせた名前をここに持ち**、
-- 「いまの値から組み立てた名前」と違う案件だけ BOX を触る。
-- 既存フォルダの付け直しも、日次ジョブがこの列の違いを拾って少しずつ進める。
--
-- 値は頭（【社内】/【社外】）を除いた名前。NULL = まだ一度も合わせていない。
-- 安全弁で触らないと決めた案件（名前に番号が無い＝人かプロジェクト管理が付けた名前）も
-- 同じ名前を書いて「見終えた」とする（毎日同じフォルダを読みに行かない）。
-- ============================================================

ALTER TABLE projects ADD COLUMN IF NOT EXISTS box_folder_name TEXT;

COMMENT ON COLUMN projects.box_folder_name IS
  'BOX フォルダ名を最後に合わせた名前（頭の【社内】/【社外】を除く）。NULL = まだ合わせていない。いまの値から組み立てた名前と違えば付け直す';
