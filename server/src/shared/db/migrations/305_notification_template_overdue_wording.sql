-- ============================================================
-- 305: 通知のひな形に残っていた「過ぎています」系の言い方を、期限の決めごとに合わせる
--
-- ── なぜ要るか（利用者からのご指摘・PR #727 の宿題④）──────────
-- 利用者から「過ぎてますとかそういう表現やめろと何度言えばわかる」と明示のご指摘があった。
-- 期限の言い方は `docs/wording.md` ルール8 で
--   期限超過 ／ N日超過 ／ 残りN日 ／ 本日 ／ 明日 ／ 期限未設定 ／ 期限内
-- に固定済み（正は `client/src/contexts/sales/pages/activityLog/dueState.ts` の `duePartsOf()`）。
--
-- PR #727 で、**実際にベルへ届く文面**（`scheduler.service.ts` がコードで組み立てる件名・本文）は
-- 「N 日超過しています」「N 日超過」「N 日経過」に直した。ところが「知らせと文面」
-- （/settings/notify）に出る**ひな形の文面**は migration 177 が入れたままで、
-- 画面には「返却予定日を過ぎています」、届く通知には「N 日超過しています」と
-- **同じ知らせが2通りの言葉**で並んでいた。ここでひな形の側を、届く文面と同じ言葉に揃える。
--
-- 対象は `notification_templates.body` の3行（id で特定。いずれも migration 177 が入れた行）:
--   inv_late      入金遅れの督促    「支払期限を過ぎた」 → 「支払期限超過の」（届く文面は「N 日超過」）
--   eq_return     機材の返却遅れ    「返却予定日を過ぎています」 → 「返却予定日から {遅延日数} 日超過しています」
--                                   （`equipmentOverdue()` の本文と同じ言い方）
--   inv_send_todo 請求書を送る（社内）「締め日を過ぎた」 → 「締め日を経過した」（届く文面は「N 日経過」）
-- `subject` は3行とも「過ぎ」を含まないので触らない。
--
-- ── ⚠️ 人が直した文面は上書きしない（大事）──────────────────────
-- この3行の本文は、system_admin が「知らせと文面」で自由に書き換えられる
-- （`notifications.routes.ts` の PUT /templates/:id）。**人が直した文を機械が戻すと、直した労力が消える。**
-- そこで UPDATE の条件は「本文が migration 177 で入れた元の文字列と**完全に一致する**行だけ」にした
-- （migration 287 の件名差し替えと同じ形）。
--   - 一致しない行（＝誰かが一度でも本文を書き換えた行）は**書き換えない**。
--     その行に「過ぎています」が残っていても、それは人が選んだ文なので機械では触らない。
--     気づいた人が「知らせと文面」の画面から直す（直すのは画面の編集で足りる）。
--   - 空白1つ・改行1つでも違えば一致しない。**部分一致（LIKE '%過ぎ%'）や replace() は使わない** —
--     人が直した文の中の「過ぎ」まで機械が書き換えてしまうため。
--   - `updated_by` は触らない。元の文字列のまま「保存」だけ押した人がいれば、その記録を消さないため
--     （機械が誰かの名前を消す理由が無い）。`updated_at` は文面が変わった事実として NOW() にする。
--
-- ── 何度流しても同じ結果（冪等）─────────────────────────────
-- 1回目で本文が新しい文面に変わると、元の文字列と一致する行がもう無いので、
-- **2回目以降は0行更新**になる。`vars` の追記も「まだ含まない行だけ」に限るので同じく0行になる。
--
-- ── 差し込み語の追記（eq_return だけ）────────────────────────
-- 新しい eq_return の本文は `{遅延日数}` を使う。この語は `equipmentOverdue()` が毎回渡している
-- （届く通知の件名「［未返却 {遅延日数}日超過］」にも出ている）ので、差し込めない語ではない。
-- 画面の「使える差し込み語」の一覧（`TemplateDialog.tsx` が `vars` を並べる）に出るよう `vars` に足す。
-- `vars` は画面から編集できない（PUT が受け取るのは subject / body / enabled だけ）機械側の列なので、
-- 本文を人が直した行でも足してよい — 足しても人の文面は1文字も変わらない。
-- `?` 演算子は使わない（`@>` で書く）。SQL の中の `?` を置き換える層を将来通っても壊れないように。
--
-- ⚠️ **過去に届いた通知（`notifications` の行）は書き換えない。** 届いた時点の文面の記録なので、
--    言い方を理由に履歴を改ざんしない。新しい言い方は次に届く通知から効く（`scheduler.service.ts` 側で済み）。
-- ============================================================

-- 入金遅れの督促（社内・ベル）
UPDATE notification_templates
   SET body = E'支払期限超過の請求があります。\n\n・請求番号：{請求番号}\n・金額：{請求金額}\n・期限：{支払期限}（{遅延日数} 日超過）',
       updated_at = NOW()
 WHERE id = 'inv_late'
   AND body = E'支払期限を過ぎた請求があります。\n\n・請求番号：{請求番号}\n・金額：{請求金額}\n・期限：{支払期限}（{遅延日数} 日超過）';

-- 機材の返却遅れ（社内・ベル）
UPDATE notification_templates
   SET body = E'{機材名} の返却予定日から {遅延日数} 日超過しています。\n借用者：{借用者名} ／ 返却予定日：{返却予定日}',
       updated_at = NOW()
 WHERE id = 'eq_return'
   AND body = E'{機材名} が返却予定日を過ぎています。\n借用者：{借用者名} ／ 予定日：{返却予定日}';

-- 機材の返却遅れ: 新しい本文が使う `{遅延日数}` を差し込み語の一覧に足す（まだ含まない行だけ）
UPDATE notification_templates
   SET vars = vars || '["{遅延日数}"]'::jsonb
 WHERE id = 'eq_return'
   AND NOT (vars @> '["{遅延日数}"]'::jsonb);

-- 請求書を送る（社内・ベル）
UPDATE notification_templates
   SET body = E'締め日を経過した請求があります。\n「請求書の送付」の文面をコピーして送ってください。\n\n・金額：{請求金額}\n・支払期限：{支払期限}',
       updated_at = NOW()
 WHERE id = 'inv_send_todo'
   AND body = E'締め日を過ぎた請求があります。\n「請求書の送付」の文面をコピーして送ってください。\n\n・金額：{請求金額}\n・支払期限：{支払期限}';
