-- ふりかえりの下書きができたことを知らせるひな形（migration 185 の KPT に対応）
--
-- ── なぜ通知が要るのか ──────────────────────────────────────
--
-- KPT の下書きは**実施日の翌日に自動で1回**起こします（指示書 2-4）。
-- 黙って作ると、案件詳細のふりかえりタブを開いた人しか気づけません。
-- ふりかえりは開かれないまま忘れられるのが常なので、
-- **できたことを担当に伝えて**、そこから開いてもらいます。
--
-- ── `enabled` を TRUE にしてある ────────────────────────────
--
-- 社内向け（`internal` / `inapp`）で、届く先も案件の担当ひとりです。
-- 社外メールのひな形が既定 FALSE なのは「送ってしまうと取り返しがつかない」ためで、
-- 社内のベルはその心配がありません。止めたい人は設定 ⑦ から止められます。
--
-- ── 既にあれば触らない ──────────────────────────────────────
--
-- 文面を直した人の変更を、次のデプロイで上書きしないためです。

INSERT INTO notification_templates
  (id, name, trigger, audience, channel, send_to, subject, body, vars, enabled, sort_order) VALUES
  ('kpt_draft', 'ふりかえりの下書き', '実施日の翌日 9:30', 'internal', 'inapp', '案件の担当',
   '［ふりかえり］{案件名} の下書きができました',
   E'{案件名} のふりかえり（KPT）の下書きを {件数} 件つくりました。\n\n**AI が起こしたものなので、まだ確かめられていません。** 中身を見て、直すか消すかしてください。\n確かめるまで隔週キープの資料には出ません。',
   '["{案件名}","{件数}"]', TRUE, 14)
ON CONFLICT (id) DO NOTHING;
