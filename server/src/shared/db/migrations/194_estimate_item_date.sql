-- 見積の明細に行ごとの日付を持たせる (v4 見積の改善要望)
--
-- ── なぜ列が要るか ──────────────────────────────────────────
--
-- 見積の行ごとに「いつの分か」（例: スタジオ利用日・機材の使用日）を
-- 添えたいという要望があったが、`estimate_items` にはその列が無かった。
-- 見積全体は `estimates.valid_until` (有効期限) を持つだけで、
-- 明細1行ごとの日付は別物 (複数日にわたる案件では行ごとに日が違う)。
--
-- **`item_date`（日付のみ・任意）を足す。** NOT NULL にしない —
-- 日付を持たない行（人件費・機材レンタルの総額など）のほうが多く、
-- 必須にすると既存の見積が保存できなくなる。

ALTER TABLE estimate_items ADD COLUMN IF NOT EXISTS item_date DATE;
