/**
 * 督促を「毎朝」から「節目だけ」にする
 *
 * ── なぜ要るか（ユーザーからの指摘）────────────────────────
 *
 * 「通知の未入金ですが／入金予定日を超えているものだけ通知するように／
 * これもゴミ通知が多い／真に必要な通知を見極めて」
 *
 * 督促の定時実行（未入金・請求書未発行・機材の返却遅れ）は、通知の `ref_date` に
 * **その日の日付**を入れていた。`notifications` の一意索引は
 * （人 × ひな形 × 対象 × ref_date）なので、日付が毎日変わると
 * **毎朝1通ずつ、解消するまで永久に**同じ督促が届く。しかも宛先が広いので
 * 「N 件 × M 人 / 日」で増える。**そうなるとベルを誰も見なくなり、
 * 本当に急ぐ1通も一緒に埋もれる**（督促を減らすのは、督促を効かせるため）。
 *
 * ここで返す文字列を `ref_date` に入れると、**同じ節目のあいだは一意索引が
 * 2通目を弾く**ので、督促は節目ごとにちょうど1通になる。
 *
 * ── ⚠️ 「ちょうどその日」で判定してはいけない ──────────────
 *
 * `daysLate === 7` のような書き方は**やってはいけない**。定時実行は
 * 「15 分ごとに起きて、過ぎていれば流す」形（`scheduler.service.ts` 冒頭）で、
 * **起きられなかった日（デプロイ中・コンテナが落ちていた日）がある**前提で
 * 作ってある。ちょうどの日で判定すると、**その日に起きられなかった督促は
 * 永久に飛ぶ**（次に判定されるのは 30 日後）。
 *
 * だから「その日が**属する**節目」を返す。1日遅れて起きても同じ鍵になり、
 * 一意索引のおかげで節目ごとにちょうど1通に落ち着く。
 *
 * ── 節目の置き方 ────────────────────────────────────────────
 *
 *   0 日以下 … 出さない（`null`。期日当日はまだ「遅れ」ではない）
 *   1〜 6 日 … `late:1`   … 気づいていない可能性がある。すぐ1通
 *   7〜29 日 … `late:7`   … 1週間。先方の締め日を1回またいだ
 *   30〜59 日 … `late:30` … 1か月。ここからは「督促の仕方」を変える段
 *   60 日以降 … 30 日ごと（`late:60` / `late:90` / `late:120` …）
 *
 * 長引くほど間隔を空けるのは、**同じ通知を出し続けても状況は動かない**から。
 * 1か月を超えたものは通知ではなく人の判断（回収・法務・値引き）の領域に入る。
 */

/** 節目の境目（日数）。ここまでは個別に置き、これ以降は `LONG_INTERVAL` ごと */
const EARLY_BUCKETS = [1, 7, 30] as const;
/** 60 日以降の間隔（日） */
const LONG_INTERVAL = 30;

/**
 * 超過 N 日のとき、その督促が属する節目の鍵（`notifications.ref_date` に入れる文字列）を返す。
 * まだ督促しないなら `null`。
 *
 * @param daysLate 期日を何日超過しているか。小数・NaN・負数も安全に受ける
 */
export function reminderBucket(daysLate: number): string | null {
  // 壊れた入力（NaN・Infinity）で督促が毎日出る形に落ちないようにする。
  // **黙って `late:1` を返さない** — 出さないほうが安全側
  if (!Number.isFinite(daysLate)) return null;
  const n = Math.floor(daysLate);
  if (n < EARLY_BUCKETS[0]) return null;

  // 60 日以降は 30 日ごと。**「その日が属する節目」**なので切り捨てで求める
  // （60〜89 → 60、90〜119 → 90。1日遅れて起きても同じ鍵になる）
  const last = EARLY_BUCKETS[EARLY_BUCKETS.length - 1];   // 30
  if (n >= last + LONG_INTERVAL) {
    return `late:${Math.floor(n / LONG_INTERVAL) * LONG_INTERVAL}`;
  }

  // 手前の3段。**大きいほうから見て、最初に届いた段が「属する節目」**
  for (let i = EARLY_BUCKETS.length - 1; i >= 0; i--) {
    if (n >= EARLY_BUCKETS[i]) return `late:${EARLY_BUCKETS[i]}`;
  }
  return null;
}

/**
 * 人に見せる「どのくらいの頻度で出るか」の一文。
 *
 * **画面にも同じ言葉で出す**（設定 ⑦「通知とテンプレート」）。
 * 頻度を減らしたことが人に伝わらないと、「通知が来ないから止まっている」と
 * 誤解されるか、逆に減ったことに気づかれずゴミ扱いのまま終わる。
 */
export const REMINDER_CADENCE_TEXT = '超過 1・7・30 日目、以後30日ごと（毎日は出しません）';
